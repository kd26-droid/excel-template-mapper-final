const IST_TIME_ZONE = 'Asia/Kolkata';

const parseHistoryDate = (value) => {
  if (!value) return null;
  const raw = String(value);
  const hasTimezone = /(?:Z|[+-]\d{2}:?\d{2})$/.test(raw);
  const date = new Date(hasTimezone ? raw : `${raw}Z`);
  return Number.isNaN(date.getTime()) ? null : date;
};

const formatIstDateTime = (value, options = {}) => {
  const date = parseHistoryDate(value);
  if (!date) return 'Unknown time';
  return date.toLocaleString('en-IN', {
    timeZone: IST_TIME_ZONE,
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    hour12: true,
    ...options
  });
};

// Vendor item templates (e.g. FactWise "Default Item.xlsx") keep help text and
// "Required / Optional" hints in the rows above the real header row, so the
// header row is often not row 1. Score the first few rows and pick the one that
// actually looks like column labels instead of assuming row 1.
const HEADER_SCAN_ROWS = 40;

const normalizeRowCells = (row = []) =>
  row.map(cell => (cell === null || cell === undefined ? '' : String(cell).trim()));

const normalizeHeaderKey = (value = '') => String(value || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
const isNumericLike = (value = '') => {
  const text = String(value || '').replace(/,/g, '').trim();
  return text !== '' && !Number.isNaN(Number(text));
};
const HEADER_KEYWORDS = [
  /\boperation\b/, /\bsequence\b/, /\bcomponent\b/, /\bitem\b/, /\bpart\b/,
  /\bdescription\b/, /\btype\b/, /\buom\b/, /\bqty\b/, /\bquantity\b/,
  /\bmanufacturer\b/, /\bmanufacture\b/, /\bmpn\b/, /\bmfr\b/, /\bdesignator/,
  /\brelease\b/, /\bstatus\b/, /\brevision\b/, /\bclassification\b/,
];
const METADATA_PATTERNS = [
  /part list for/, /report date/, /^description:?$/, /^required\b/, /^optional\b/,
  /generated by/, /printed on/, /page \d+/, /^plm$/, /^bom report$/,
];

const scoreHeaderRow = (rows = [], rowIndex = 0) => {
  const row = rows[rowIndex] || [];
  const cells = normalizeRowCells(row);
  const filled = cells.filter(cell => cell !== '');
  if (filled.length === 0) return Number.NEGATIVE_INFINITY;

  const count = filled.length;
  const avgLength = filled.reduce((sum, cell) => sum + cell.length, 0) / count;
  const longCells = filled.filter(cell => cell.length > 60).length;
  const proseCells = filled.filter(cell => /[.!?](\s|$)/.test(cell) || cell.split(/\s+/).length > 8).length;
  const numericCells = filled.filter(isNumericLike).length;
  const normalized = filled.map(normalizeHeaderKey);
  const keywordHits = normalized.filter(cell => HEADER_KEYWORDS.some(pattern => pattern.test(cell))).length;
  const metadataHits = normalized.filter(cell => METADATA_PATTERNS.some(pattern => pattern.test(cell))).length;
  const uniqueRatio = new Set(normalized).size / count;
  const indexes = cells.map((cell, index) => (cell ? index : -1)).filter(index => index >= 0);
  const nextRows = rows.slice(rowIndex + 1, rowIndex + 9).map(normalizeRowCells);
  const supportedColumns = indexes.filter(index => nextRows.some(nextRow => nextRow[index])).length;
  const dataRowsBelow = nextRows.filter(nextRow => indexes.some(index => nextRow[index])).length;
  const mostlyUpper = filled.filter(cell => /[A-Z]/.test(cell) && cell === cell.toUpperCase() && /[A-Z]{2}/.test(cell)).length;
  const shortLabelRatio = filled.filter(cell => cell.length <= 35 && cell.split(/\s+/).length <= 5).length / count;
  const supportRatio = count ? supportedColumns / count : 0;
  const numericPenalty = supportRatio >= 0.5 ? 6 : 25;

  return (
    count * 2.4                        // wide rows are more likely to be the header
    + keywordHits * 5                  // known BOM/table labels are strong signals
    + supportedColumns * 1.4           // real headers usually have data underneath
    + dataRowsBelow * 1.2
    + shortLabelRatio * 8
    + mostlyUpper * 0.7
    - (longCells / count) * 40         // help text is long
    - (proseCells / count) * 30        // help text reads like sentences
    - (numericCells / count) * numericPenalty
    - metadataHits * 18                // report titles/date rows are not headers
    - (count <= 2 ? 20 : 0)
    - Math.max(0, avgLength - 30) * 0.6
    + uniqueRatio * 10                 // column labels are mostly distinct
  );
};

const readSheetRows = (workbook, sheetName) => {
  if (!workbook || !sheetName || !workbook.Sheets || !workbook.Sheets[sheetName]) return [];
  const ws = workbook.Sheets[sheetName];
  const opts = { header: 1, raw: false, defval: '', blankrows: true };
  // Force reading from literal row A1 so a blank leading row is INCLUDED. Excel's
  // used-range can start at row 2, which makes XLSX drop the blank row 1 — then
  // the frontend's row numbers no longer match the backend (pandas), which counts
  // that blank row. Anchoring at A1 keeps both sides on the same row numbering.
  try {
    if (ws['!ref']) {
      const r = XLSX.utils.decode_range(ws['!ref']);
      if (r.s.r > 0 || r.s.c > 0) {
        r.s.r = 0;
        r.s.c = 0;
        opts.range = XLSX.utils.encode_range(r);
      }
    }
  } catch (_) { /* fall back to default range */ }
  return XLSX.utils.sheet_to_json(ws, opts);
};

// Returns a 1-based row number, matching the "Header Row" field.
const detectHeaderRow = (workbook, sheetName) => {
  const rows = readSheetRows(workbook, sheetName).slice(0, HEADER_SCAN_ROWS);
  let bestRow = 0;
  let bestScore = Number.NEGATIVE_INFINITY;

  rows.forEach((row, index) => {
    const score = scoreHeaderRow(rows, index);
    if (score > bestScore) {
      bestScore = score;
      bestRow = index;
    }
  });

  return bestRow + 1;
};

const getUsableColumnDescriptors = (rows, headerIndex) => {
  const headerRow = normalizeRowCells(rows[Math.max(0, headerIndex)] || []);
  const dataRows = rows.slice(headerIndex + 1).map(normalizeRowCells);
  const maxLength = Math.max(
    headerRow.length,
    ...dataRows.map(row => row.length),
    0
  );
  const used = new Map();
  const descriptors = [];
  for (let index = 0; index < maxLength; index += 1) {
    const rawHeader = headerRow[index] || '';
    const hasHeader = rawHeader !== '';
    const hasData = dataRows.some(row => row[index]);
    // Keep every named column, even if it looks generic ("A", "1", "Column X")
    // or has no current data. Also keep blank-header columns if any data exists.
    // Only truly empty columns with no header and no data are hidden.
    if (!hasHeader && !hasData) continue;
    const base = rawHeader || `Column ${index + 1}`;
    const count = used.get(base) || 0;
    used.set(base, count + 1);
    descriptors.push({
      index,
      header: count === 0 ? base : `${base} ${count + 1}`,
      isGenerated: !rawHeader,
    });
  }
  return descriptors;
};

const readHeadersAtRow = (workbook, sheetName, headerRow) => {
  const rows = readSheetRows(workbook, sheetName);
  const headerIndex = Math.max(0, (Number(headerRow) || 1) - 1);
  return getUsableColumnDescriptors(rows, headerIndex).map(column => column.header);
};

const normalizeSheetJoinKey = value => String(value ?? '')
  .normalize('NFKC')
  .replace(/[\u200B-\u200D\uFEFF]/g, '')
  .replace(/\u00a0/g, ' ')
  .replace(/[‐‑‒–—−]/g, '-')
  .replace(/^'/, '')
  .replace(/\.0+$/, '')
  .replace(/\s+/g, ' ')
  .trim()
  .toLowerCase();

const cleanSheetJoinValue = value => String(value ?? '').trim();

const uniqueSheetJoinValues = values => {
  const seen = new Set();
  return values
    .map(cleanSheetJoinValue)
    .filter(value => {
      const key = value.toLowerCase();
      if (!value || seen.has(key)) return false;
      seen.add(key);
      return true;
    });
};

const DEFAULT_GROUPED_DETAIL_IGNORE_PATTERNS = [
  '^[^:]{2,40}:\\s*.+',
  '^note\\b',
  '^remark\\b',
  '^specification\\b',
].join('\n');

const compileGroupedDetailIgnorePatterns = (patternText = DEFAULT_GROUPED_DETAIL_IGNORE_PATTERNS) => (
  String(patternText || '')
    .split(/\r?\n/)
    .map(pattern => pattern.trim())
    .filter(Boolean)
    .map(pattern => {
      try {
        return new RegExp(pattern, 'i');
      } catch (err) {
        return null;
      }
    })
    .filter(Boolean)
);

const looksLikeGroupedDetailItem = value => {
  const text = cleanSheetJoinValue(value);
  if (!text) return false;
  if (text.includes(':')) return false;
  if (text.length > 80) return false;
  if (text.split(/\s+/).length > 5) return false;
  return /[0-9]/.test(text) || /^[A-Z]{1,6}[A-Za-z0-9,./+_-]{2,}$/i.test(text);
};

const splitGroupedDetailValue = (value, mode = 'auto', customDelimiter = '') => {
  const text = cleanSheetJoinValue(value);
  if (!text) return { value: '', manufacturer: '' };
  if (mode === 'none') return { value: text, manufacturer: '' };

  const splitAt = (delimiter, preferLast = false) => {
    const index = preferLast ? text.lastIndexOf(delimiter) : text.indexOf(delimiter);
    if (index <= 0) return null;
    const left = cleanSheetJoinValue(text.slice(0, index));
    const right = cleanSheetJoinValue(text.slice(index + delimiter.length));
    if (!left || !right || right.length > 80) return null;
    return { value: left, manufacturer: right };
  };

  if (mode === 'custom') return customDelimiter ? (splitAt(customDelimiter) || { value: text, manufacturer: '' }) : { value: text, manufacturer: '' };
  if (mode === 'pipe') return splitAt('|') || { value: text, manufacturer: '' };
  if (mode === 'semicolon') return splitAt(';') || { value: text, manufacturer: '' };
  if (mode === 'slash') return splitAt('/', true) || { value: text, manufacturer: '' };

  return splitAt('|')
    || splitAt(';')
    || splitAt('/', true)
    || { value: text, manufacturer: '' };
};

// Stack several same-layout sheets into one sheet and return it as an .xlsx File.
// The first selected sheet's header is canonical; each sheet's rows are aligned to
// it by column NAME (so column-order differences are tolerated). The combined
// sheet always has its header on row 1, so it uploads like any normal single sheet.
const buildCombinedSheetFile = (workbook, sheetNames, headerRow, fileName) => {
  const hr = Math.max(1, Number(headerRow) || 1);
  let canonical = null;
  const dataRows = [];
  (sheetNames || []).forEach((sheet) => {
    const rows = readSheetRows(workbook, sheet);
    if (!rows || rows.length < hr) return;
    const columns = getUsableColumnDescriptors(rows, hr - 1);
    const header = columns.map((column) => column.header);
    if (!canonical) canonical = header.slice();
    const idxByName = {};
    columns.forEach((column) => { if (column.header && !(column.header in idxByName)) idxByName[column.header] = column.index; });
    for (let r = hr; r < rows.length; r += 1) {
      const row = rows[r] || [];
      if (row.every((c) => String(c ?? '').trim() === '')) continue; // skip blank lines
      dataRows.push(canonical.map((name) => {
        const si = idxByName[name];
        return si === undefined ? '' : (row[si] ?? '');
      }));
    }
  });
  if (!canonical) return null;
  const ws = XLSX.utils.aoa_to_sheet([canonical, ...dataRows]);
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, 'Combined');
  const out = XLSX.write(wb, { bookType: 'xlsx', type: 'array' });
  const blob = new Blob([out], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
  const base = String(fileName || 'combined').replace(/\.(xlsx|xlsm|xls|csv)$/i, '');
  return { file: new File([blob], `${base} (combined).xlsx`, { type: blob.type }), rows: dataRows.length };
};

const asText = (value) => (value === null || value === undefined ? '' : String(value).trim());

const makeUniqueHeaders = (headers = []) => {
  const used = new Map();
  return headers.map((header, index) => {
    const base = asText(header) || `Column ${index + 1}`;
    const count = used.get(base) || 0;
    used.set(base, count + 1);
    return count === 0 ? base : `${base} ${count + 1}`;
  });
};

const createWorkbookFromObjects = (rows, headers, sheetLabel = 'PDF_Source') => {
  const worksheet = XLSX.utils.aoa_to_sheet([
    headers,
    ...rows.map((row) => headers.map((header) => row[header] || '')),
  ]);
  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, sheetLabel.slice(0, 31) || 'PDF_Source');
  return workbook;
};

const createWorkbookFileFromWorkbook = (workbook, fileName) => {
  const output = XLSX.write(workbook, { bookType: 'xlsx', type: 'array' });
  const blob = new Blob([output], {
    type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  });
  return new File([blob], fileName, { type: blob.type });
};

const normalizePdfRowsForWorkbook = (payload, sourceFile) => {
  const pdfHeaders = makeUniqueHeaders(payload?.headers || []);
  const rawRows = Array.isArray(payload?.data) ? payload.data : [];
  const decision = payload?.decision;
  const decisionLabel = typeof decision === 'string'
    ? decision
    : (decision?.winner || decision?.method || 'best extraction');

  if (!pdfHeaders.length || !rawRows.length) {
    return { headers: [], rows: [] };
  }

  const rows = rawRows
    .map((row, index) => {
      const mapped = {
        'Source file': sourceFile,
        'Source sheet': `PDF ${decisionLabel}`,
        __sourceRow: index + 1,
      };
      pdfHeaders.forEach((header, headerIndex) => {
        mapped[header] = asText(Array.isArray(row) ? row[headerIndex] : row?.[header]);
      });
      return mapped;
    })
    .filter((row) => pdfHeaders.some((header) => asText(row[header])));

  return {
    headers: ['Source file', 'Source sheet', ...pdfHeaders],
    rows,
  };
};

const normalizePdfTablesForWorkbook = (payload, sourceFile) => {
  const tables = Array.isArray(payload?.tables) ? payload.tables : [];
  const sources = tables.map((table, tableIndex) => {
    const tableHeaders = makeUniqueHeaders(table?.headers || []);
    const rawRows = Array.isArray(table?.data) ? table.data : [];
    const pageLabel = table?.page_number ? `page ${table.page_number}` : `table ${tableIndex + 1}`;
    const rows = rawRows
      .map((row, rowIndex) => {
        const mapped = {
          'Source file': sourceFile,
          'Source sheet': `PDF ${pageLabel}`,
          __sourceRow: rowIndex + 1,
        };
        tableHeaders.forEach((header, headerIndex) => {
          mapped[header] = asText(Array.isArray(row) ? row[headerIndex] : row?.[header]);
        });
        return mapped;
      })
      .filter((row) => tableHeaders.some((header) => asText(row[header])));

    return {
      headers: ['Source file', 'Source sheet', ...tableHeaders],
      rows,
    };
  }).filter((source) => source.headers.length > 2 && source.rows.length);

  if (!sources.length) return { headers: [], rows: [] };

  const headers = [];
  sources.forEach((source) => {
    source.headers.forEach((header) => {
      if (!headers.includes(header)) headers.push(header);
    });
  });

  return {
    headers,
    rows: sources.flatMap((source) => source.rows),
  };
};

const createExtractedPdfWorkbook = (payload, sourceFileName = 'PDF source') => {
  const normalizedTables = normalizePdfTablesForWorkbook(payload, sourceFileName);
  const normalized = normalizedTables.rows.length
    ? normalizedTables
    : normalizePdfRowsForWorkbook(payload, sourceFileName);

  if (!normalized.headers.length || !normalized.rows.length) {
    throw new Error('No usable table rows were extracted from this PDF.');
  }

  const workbook = createWorkbookFromObjects(normalized.rows, normalized.headers, 'PDF_Source');
  const safeBase = String(sourceFileName || 'pdf-source').replace(/\.[^.]+$/, '') || 'pdf-source';
  const workbookFile = createWorkbookFileFromWorkbook(workbook, `${safeBase} (extracted).xlsx`);

  return {
    workbook,
    file: workbookFile,
    sheetNames: workbook.SheetNames || ['PDF_Source'],
    rowCount: normalized.rows.length,
    columnCount: normalized.headers.length,
    rows: normalized.rows,
    headers: normalized.headers,
    extractionData: payload,
  };
};


